-- V1: the schema exactly as Hibernate "ddl-auto: update" created it before
-- Flyway was introduced. Existing databases are baselined at this version
-- (spring.flyway.baseline-on-migrate) and only receive V2+; new databases
-- are created from scratch by running V1 and everything after it.

CREATE TABLE admins (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) UNIQUE,
    password VARCHAR(255),
    email    VARCHAR(255),
    name     VARCHAR(255),
    role     VARCHAR(255)
);

CREATE TABLE bhojana_shala (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255),
    capacity     INTEGER,
    timings      VARCHAR(255),
    service_type VARCHAR(255),
    status       VARCHAR(255),
    active       BOOLEAN NOT NULL
);

CREATE TABLE board_members (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(255),
    position          VARCHAR(255),
    department        VARCHAR(255),
    phone_number      VARCHAR(255),
    email             VARCHAR(255),
    biography         VARCHAR(3000),
    profile_image_url VARCHAR(500),
    status            VARCHAR(255)
);

CREATE TABLE board_member_services (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_member_id     BIGINT NOT NULL REFERENCES board_members (id),
    service_title       VARCHAR(255),
    service_description VARCHAR(1000),
    service_start_date  DATE,
    service_end_date    DATE,
    status              VARCHAR(255),
    remarks             VARCHAR(255)
);

CREATE TABLE contact_info (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255),
    phone   VARCHAR(255),
    email   VARCHAR(255),
    subject VARCHAR(255),
    message VARCHAR(2000),
    active  BOOLEAN NOT NULL
);

CREATE TABLE donors (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) UNIQUE,
    name            VARCHAR(255),
    donation_amount FLOAT(53),
    donation_type   VARCHAR(255),
    phone_number    VARCHAR(255),
    address         VARCHAR(255),
    city            VARCHAR(255),
    state           VARCHAR(255),
    zip_code        VARCHAR(255)
);

CREATE TABLE email_subscriptions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    full_name       VARCHAR(255) NOT NULL,
    phone           VARCHAR(50),
    preferences     TEXT,
    is_active       BOOLEAN NOT NULL,
    subscribed_at   TIMESTAMP(6) NOT NULL,
    unsubscribed_at TIMESTAMP(6),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6)
);

CREATE TABLE events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name  VARCHAR(255),
    description VARCHAR(2000),
    event_date  DATE,
    start_time  TIME(6),
    end_time    TIME(6),
    location    VARCHAR(255),
    category    VARCHAR(255),
    status      VARCHAR(255),
    image_url   TEXT
);

CREATE TABLE event_registrations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          BIGINT NOT NULL REFERENCES events (id),
    registration_date TIMESTAMP(6) NOT NULL,
    total_members     INTEGER,
    status            VARCHAR(255)
);

CREATE TABLE event_registration_members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL REFERENCES event_registrations (id),
    name            VARCHAR(255) NOT NULL,
    surname         VARCHAR(255),
    address         VARCHAR(500),
    phone_no        VARCHAR(255) NOT NULL,
    email           VARCHAR(255) NOT NULL
);

CREATE TABLE goshala (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255),
    number_of_cows INTEGER,
    location       VARCHAR(255),
    caretaker      VARCHAR(255),
    daily_routine  VARCHAR(1000),
    status         VARCHAR(255),
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6)
);

CREATE TABLE photos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_name    VARCHAR(255),
    photo_type    VARCHAR(255),
    related_id    BIGINT,
    photo_data    TEXT,
    photo_url     VARCHAR(255),
    uploaded_by   VARCHAR(255),
    uploaded_date TIMESTAMP(6),
    status        VARCHAR(255),
    description   VARCHAR(255),
    file_size     BIGINT,
    mime_type     VARCHAR(100)
);

CREATE TABLE service_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    price       VARCHAR(255),
    description VARCHAR(1000),
    details     VARCHAR(2000),
    active      BOOLEAN NOT NULL
);

CREATE TABLE sponsorships (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_name VARCHAR(255),
    amount     FLOAT(53),
    purpose    VARCHAR(255),
    date       DATE,
    status     VARCHAR(255),
    active     BOOLEAN NOT NULL
);

CREATE TABLE staff (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name         VARCHAR(255),
    position          VARCHAR(255),
    department        VARCHAR(255),
    phone_number      VARCHAR(255),
    email             VARCHAR(255),
    biography         VARCHAR(3000),
    profile_image_url VARCHAR(500),
    status            VARCHAR(255)
);

CREATE TABLE subscription_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES email_subscriptions (id),
    action_type     VARCHAR(255) NOT NULL,
    details         TEXT,
    created_at      TIMESTAMP(6) NOT NULL,
    email_subject   VARCHAR(255),
    error_message   VARCHAR(255)
);

CREATE TABLE temple_timings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week   VARCHAR(255),
    opening_time  TIME(6),
    closing_time  TIME(6),
    special_notes VARCHAR(255)
);

CREATE TABLE vidyalaya (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255),
    description       VARCHAR(2000),
    director          VARCHAR(255),
    students_enrolled INTEGER,
    subjects          VARCHAR(255),
    operating_days    VARCHAR(255),
    timings           VARCHAR(255),
    status            VARCHAR(255),
    created_at        TIMESTAMP(6),
    updated_at        TIMESTAMP(6)
);
